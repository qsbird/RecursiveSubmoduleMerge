def asset_directories() -> list[Path]:
    directories: list[Path] = []
    seen: set[Path] = set()

    def add(path: Path) -> None:
        resolved = path.resolve()
        if resolved in seen:
            return
        seen.add(resolved)
        directories.append(resolved)

    add(Path(__file__).resolve().parents[1] / "assets")
    meipass = getattr(sys, "_MEIPASS", None)
    if isinstance(meipass, str) and meipass:
        add(Path(meipass) / "assets")
    add(Path(sys.executable).resolve().parent / "assets")
    add(Path.cwd() / "assets")
    return directories


def resolve_window_icon_png() -> Path | None:
    for folder in asset_directories():
        candidate = folder / WINDOW_ICON_PNG_NAME
        if candidate.is_file():
            return candidate
    return None


def apply_window_icon(
    root: Any,
    *,
    photo_image_factory: Callable[..., Any] | None = None,
    icon_path: Path | str | None = None,
) -> bool:
    if photo_image_factory is None:
        import tkinter as tk

        photo_image_factory = tk.PhotoImage

    candidates: list[Path] = []
    if icon_path is not None:
        candidates.append(Path(icon_path))
    else:
        resolved = resolve_window_icon_png()
        if resolved is not None:
            candidates.append(resolved)

    image = None
    try:
        for path in candidates:
            if not path.is_file():
                continue
            image = photo_image_factory(master=root, file=str(path))
            break
        if image is None:
            image = photo_image_factory(master=root, data=WINDOW_ICON_PNG_BASE64)
        root.iconphoto(True, image)
        root._merge_tool_window_icon = image
    except Exception:  # noqa: BLE001 - icon setup must never block the GUI.
        return False
    return True
